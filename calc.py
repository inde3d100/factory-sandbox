"""A tiny calculator."""


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    """Return the product of a and b."""
    return a * b


def divide(a, b):
    """Return a divided by b."""
    return a / b


def power(a, b):
    """Return a raised to the power of b."""
    return a ** b
